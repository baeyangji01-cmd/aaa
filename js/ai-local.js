function terms(text){
  const t=String(text||'').replace(/\r/g,'');
  if(!/임대인|임차인|보증금|특약|계약/.test(t))
    return{grade:'unknown',headline:'특약사항으로 보이지 않아요. 계약서의 특약 부분을 붙여넣어 주세요.',present:[],missing:[],risky:[]};
  const clauses=t.split(/\n+/).map(s=>s.replace(/^\s*(\d+[.)]|[-•·○])\s*/,'').trim()).filter(s=>s.length>5&&!/^\[예시\]/.test(s));
  const short=s=>s.length>90?s.slice(0,88)+'…':s;
  const risky=[],used=new Set();
  clauses.forEach((c,i)=>{const r=RISKY.find(x=>x.re.test(c));if(r){risky.push({quote:short(c),why:r.why,fix:r.fix});used.add(i)}});
  const present=[],missing=[];
  PROTECT.forEach(p=>{const i=clauses.findIndex((c,j)=>!used.has(j)&&p.re.test(c));
    if(i>=0)present.push({title:p.title,quote:short(clauses[i])});else missing.push({title:p.title,why:p.why,suggested:p.suggested,must:p.must})});
  const keep=clauses.findIndex((c,j)=>!used.has(j)&&/(등기부?|권리).{0,20}(유지|변동\s*없)/.test(c));
  if(keep>=0&&!present.some(p=>p.quote===short(clauses[keep])))present.push({title:'잔금일까지 등기부 상태 유지',quote:short(clauses[keep])});
  const mustMiss=missing.filter(m=>m.must).length;
  const grade=risky.length||mustMiss?'danger':missing.length?'caution':'safe';
  const headline=risky.length?`세입자에게 불리한 조항이 ${risky.length}개 있고, 보호 조항이 ${missing.length}개 빠져 있어요.`
    :mustMiss?`꼭 필요한 보호 조항 ${mustMiss}개가 빠져 있어요. 도장 찍기 전에 넣어 달라고 하세요.`
    :missing.length?`기본은 갖췄지만 보호 조항 ${missing.length}개를 더 넣으면 좋아요.`
    :'세입자를 지키는 주요 조항이 잘 들어 있어요.';
  return{grade,headline,present,missing:missing.map(({must,...m})=>m),risky}}

